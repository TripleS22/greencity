        '}' => '10100011110', '~' => '10001011110',
    ];

    private static string $START_B = '11010010000';
    private static string $STOP = '1100011101011';

    public static function generateSvg(string $data, int $height = 50, int $barWidth = 1): string
    {
        $binary = self::$START_B;
        $checksum = 104; // Start B value

        for ($i = 0; $i < strlen($data); $i++) {
            $char = $data[$i];
            if (isset(self::$CODE128B[$char])) {
                $binary .= self::$CODE128B[$char];
                $checksum += (ord($char) - 32) * ($i + 1);
            }
        }

        // Checksum character
        $checksumVal = $checksum % 103;
        $checksumChar = chr($checksumVal + 32);
        if ($checksumVal >= 95) $checksumChar = chr($checksumVal + 105 - 95);
        if (isset(self::$CODE128B[$checksumChar])) {
            $binary .= self::$CODE128B[$checksumChar];
        }

        $binary .= self::$STOP;

        $width = strlen($binary) * $barWidth;
        $svg = '<?xml version="1.0" encoding="UTF-8"?>';
        $svg .= '<svg xmlns="http://www.w3.org/2000/svg" width="' . $width . '" height="' . $height . '" viewBox="0 0 ' . $width . ' ' . $height . '">';

        $x = 0;
        for ($i = 0; $i < strlen($binary); $i++) {
            if ($binary[$i] === '1') {
                $svg .= '<rect x="' . ($x * $barWidth) . '" y="0" width="' . $barWidth . '" height="' . $height . '" fill="#000000"/>';
            }
            $x++;
        }

        $svg .= '</svg>';
        return 'data:image/svg+xml;base64,' . base64_encode($svg);
    }
}
